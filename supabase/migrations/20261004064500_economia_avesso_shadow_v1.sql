create or replace function private.record_avesso_activity_heartbeat(p_user_id uuid)
returns integer language plpgsql security definer set search_path='' as $$
declare v_settings public.avesso_economy_settings%rowtype; v_last_seen timestamptz; v_session public.avesso_activity_sessions%rowtype; v_delta integer:=0; v_target_blocks integer:=0; v_reward integer:=0; v_day text;
begin
  if p_user_id is null or public.is_user_suspended(p_user_id) then return 0; end if;
  select * into v_settings from public.avesso_economy_settings where id='global'; if v_settings.mode='off' then return 0; end if;
  select p.last_seen into v_last_seen from public.profiles p where p.id=p_user_id; if v_last_seen is null or v_last_seen<now()-make_interval(secs=>v_settings.active_window_seconds) then return 0; end if;
  select * into v_session from public.avesso_activity_sessions s where s.user_id=p_user_id and s.ended_at is null for update;
  if found and (v_session.last_heartbeat_at<now()-interval '5 minutes' or (v_session.started_at at time zone 'UTC')::date<>(now() at time zone 'UTC')::date) then update public.avesso_activity_sessions set ended_at=now(),updated_at=now() where id=v_session.id; v_session.id:=null; end if;
  if v_session.id is null then insert into public.avesso_activity_sessions(user_id,started_at,last_active_at,last_heartbeat_at) values(p_user_id,now(),now(),now()) returning * into v_session; return 0; end if;
  v_delta:=least(60,greatest(0,extract(epoch from (now()-v_session.last_heartbeat_at))::integer));
  update public.avesso_activity_sessions set last_active_at=now(),last_heartbeat_at=now(),qualified_seconds=qualified_seconds+v_delta,updated_at=now() where id=v_session.id returning * into v_session;
  v_target_blocks:=floor(v_session.qualified_seconds::numeric/v_settings.presence_block_seconds)::integer;
  if v_target_blocks>v_session.rewarded_blocks then v_day:=to_char(now() at time zone 'UTC','YYYY-MM-DD'); v_reward:=private.award_avesso_reward(p_user_id,'presence_block','activity_session',v_session.id::text,jsonb_build_object('block',v_session.rewarded_blocks+1),'presence_block:'||p_user_id::text||':'||v_day||':'||(v_session.rewarded_blocks+1)::text); if v_reward>0 then update public.avesso_activity_sessions set rewarded_blocks=rewarded_blocks+1,updated_at=now() where id=v_session.id; end if; end if;
  return v_reward;
end;$$;
revoke all on function private.record_avesso_activity_heartbeat(uuid) from public,anon,authenticated;

