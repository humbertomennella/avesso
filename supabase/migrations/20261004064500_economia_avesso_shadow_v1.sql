create or replace function private.avesso_pulse_multiplier(p_user_id uuid)
returns numeric language plpgsql stable security definer set search_path='' as $$
declare v_days integer:=0; v_categories integer:=0;
begin
  select count(distinct (l.created_at at time zone 'UTC')::date),count(distinct r.category)
  into v_days,v_categories
  from public.avesso_wallet_ledger l join public.avesso_reward_rules r on r.rule_key=l.rule_key
  where l.user_id=p_user_id and l.transaction_type='earn' and l.amount>0 and r.counts_toward_pulse and l.created_at>=now()-interval '7 days';
  if v_days>=6 and v_categories>=5 then return 1.15; end if;
  if v_days>=5 and v_categories>=4 then return 1.10; end if;
  if v_days>=3 and v_categories>=3 then return 1.05; end if;
  return 1.00;
end;$$;
revoke all on function private.avesso_pulse_multiplier(uuid) from public,anon,authenticated;

create or replace function private.award_avesso_reward(p_user_id uuid,p_rule_key text,p_source_type text,p_source_id text,p_metadata jsonb,p_idempotency_key text)
returns integer language plpgsql security definer set search_path='' as $$
declare
  v_rule public.avesso_reward_rules%rowtype; v_mode text; v_global_cap integer; v_rule_today integer:=0; v_global_today integer:=0; v_multiplier numeric:=1.00; v_award integer:=0; v_inserted bigint;
begin
  if p_user_id is null then return 0; end if;
  if not exists(select 1 from public.profiles p where p.id=p_user_id) then return 0; end if;
  if public.is_user_suspended(p_user_id) then return 0; end if;
  select s.mode,s.global_daily_cap into v_mode,v_global_cap from public.avesso_economy_settings s where s.id='global';
  if coalesce(v_mode,'off')='off' then return 0; end if;
  select * into v_rule from public.avesso_reward_rules r where r.rule_key=p_rule_key and r.enabled;
  if not found or v_rule.base_amount<=0 then return 0; end if;
  insert into public.avesso_wallets(user_id) values(p_user_id) on conflict(user_id) do nothing;
  perform 1 from public.avesso_wallets w where w.user_id=p_user_id for update;
  if exists(select 1 from public.avesso_wallet_ledger l where l.idempotency_key=p_idempotency_key) then return 0; end if;
  select coalesce(sum(l.amount),0)::integer into v_rule_today from public.avesso_wallet_ledger l where l.user_id=p_user_id and l.rule_key=p_rule_key and l.transaction_type='earn' and l.created_at>=date_trunc('day',now());
  if v_rule.daily_cap>0 and v_rule_today>=v_rule.daily_cap then return 0; end if;
  if v_rule.counts_toward_daily_cap then
    select coalesce(sum(l.amount),0)::integer into v_global_today from public.avesso_wallet_ledger l join public.avesso_reward_rules r on r.rule_key=l.rule_key where l.user_id=p_user_id and l.transaction_type='earn' and l.created_at>=date_trunc('day',now()) and r.counts_toward_daily_cap;
    if v_global_cap>0 and v_global_today>=v_global_cap then return 0; end if;
  end if;
  if v_rule.multiplier_eligible then v_multiplier:=private.avesso_pulse_multiplier(p_user_id); end if;
  v_award:=round(v_rule.base_amount::numeric*v_multiplier)::integer;
  if v_rule.daily_cap>0 then v_award:=least(v_award,greatest(0,v_rule.daily_cap-v_rule_today)); end if;
  if v_rule.counts_toward_daily_cap and v_global_cap>0 then v_award:=least(v_award,greatest(0,v_global_cap-v_global_today)); end if;
  if v_award<=0 then return 0; end if;
  insert into public.avesso_wallet_ledger(user_id,transaction_type,rule_key,source_type,source_id,amount,idempotency_key,metadata)
  values(p_user_id,'earn',p_rule_key,left(p_source_type,80),left(p_source_id,180),v_award,left(p_idempotency_key,260),coalesce(p_metadata,'{}'::jsonb))
  on conflict(idempotency_key) do nothing returning id into v_inserted;
  if v_inserted is null then return 0; end if;
  update public.avesso_wallets set balance=balance+v_award,lifetime_earned=lifetime_earned+v_award,updated_at=now() where user_id=p_user_id;
  return v_award;
end;$$;
revoke all on function private.award_avesso_reward(uuid,text,text,text,jsonb,text) from public,anon,authenticated;

create or replace function private.reverse_avesso_reward(p_user_id uuid,p_original_key text,p_reason text)
returns integer language plpgsql security definer set search_path='' as $$
declare v_original public.avesso_wallet_ledger%rowtype; v_inserted bigint;
begin
  select * into v_original from public.avesso_wallet_ledger l where l.user_id=p_user_id and l.idempotency_key=p_original_key and l.transaction_type='earn';
  if not found then return 0; end if;
  perform 1 from public.avesso_wallets w where w.user_id=p_user_id for update;
  insert into public.avesso_wallet_ledger(user_id,transaction_type,rule_key,source_type,source_id,amount,idempotency_key,metadata)
  values(p_user_id,'reversal',v_original.rule_key,v_original.source_type,v_original.source_id,-v_original.amount,left('reversal:'||p_original_key,260),jsonb_build_object('reason',left(coalesce(p_reason,'reversal'),160),'original_ledger_id',v_original.id))
  on conflict(idempotency_key) do nothing returning id into v_inserted;
  if v_inserted is null then return 0; end if;
  update public.avesso_wallets set balance=greatest(0,balance-v_original.amount),lifetime_earned=greatest(0,lifetime_earned-v_original.amount),updated_at=now() where user_id=p_user_id;
  return v_original.amount;
end;$$;
revoke all on function private.reverse_avesso_reward(uuid,text,text) from public,anon,authenticated;

