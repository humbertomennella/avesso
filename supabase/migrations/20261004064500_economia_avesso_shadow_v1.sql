create table public.avesso_economy_settings (
  id text primary key default 'global' check (id='global'),
  mode text not null default 'shadow' check (mode in ('off','shadow','live')),
  global_daily_cap integer not null default 180 check (global_daily_cap >= 0),
  presence_block_seconds integer not null default 1800 check (presence_block_seconds between 300 and 7200),
  active_window_seconds integer not null default 120 check (active_window_seconds between 30 and 600),
  updated_at timestamptz not null default now()
);

create table public.avesso_reward_rules (
  rule_key text primary key check (rule_key ~ '^[a-z0-9_]{2,60}$'),
  label text not null check (char_length(label) between 2 and 100),
  category text not null check (category ~ '^[a-z0-9_]{2,40}$'),
  base_amount integer not null check (base_amount >= 0),
  daily_cap integer not null default 0 check (daily_cap >= 0),
  cooldown_seconds integer not null default 0 check (cooldown_seconds >= 0),
  multiplier_eligible boolean not null default true,
  counts_toward_daily_cap boolean not null default true,
  counts_toward_pulse boolean not null default true,
  enabled boolean not null default true,
  config jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.avesso_wallets (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  balance bigint not null default 0 check (balance >= 0),
  lifetime_earned bigint not null default 0 check (lifetime_earned >= 0),
  lifetime_spent bigint not null default 0 check (lifetime_spent >= 0),
  updated_at timestamptz not null default now()
);

create table public.avesso_wallet_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  transaction_type text not null check (transaction_type in ('earn','spend','transfer_in','transfer_out','reversal','admin_adjustment')),
  rule_key text references public.avesso_reward_rules(rule_key) on delete restrict,
  source_type text not null check (char_length(source_type) between 1 and 80),
  source_id text not null check (char_length(source_id) between 1 and 180),
  amount integer not null check (amount <> 0),
  idempotency_key text not null unique check (char_length(idempotency_key) between 3 and 260),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index avesso_wallet_ledger_user_created_idx on public.avesso_wallet_ledger(user_id,created_at desc);
create index avesso_wallet_ledger_user_rule_created_idx on public.avesso_wallet_ledger(user_id,rule_key,created_at desc);

create table public.avesso_activity_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  started_at timestamptz not null default now(),
  last_active_at timestamptz not null default now(),
  last_heartbeat_at timestamptz not null default now(),
  qualified_seconds integer not null default 0 check (qualified_seconds >= 0),
  rewarded_blocks integer not null default 0 check (rewarded_blocks >= 0),
  ended_at timestamptz,
  updated_at timestamptz not null default now()
);
create unique index avesso_activity_sessions_one_open_idx on public.avesso_activity_sessions(user_id) where ended_at is null;
create index avesso_activity_sessions_user_started_idx on public.avesso_activity_sessions(user_id,started_at desc);

