update public.avesso_wallets w
set balance=x.net,lifetime_earned=x.earned,lifetime_spent=x.spent,updated_at=now()
from (
  select u.id as user_id,
    coalesce(sum(l.amount),0)::bigint as net,
    coalesce(sum(case when l.transaction_type='earn' and l.amount>0 then l.amount else 0 end),0)::bigint as earned,
    coalesce(sum(case when l.transaction_type in ('spend','transfer_out') and l.amount<0 then -l.amount else 0 end),0)::bigint as spent
  from public.profiles u left join public.avesso_wallet_ledger l on l.user_id=u.id group by u.id
) x
where w.user_id=x.user_id;

create or replace view private.avesso_economy_shadow_audit as
select w.user_id,w.balance,w.lifetime_earned,w.lifetime_spent,
  coalesce(sum(l.amount),0)::bigint as ledger_net,
  count(l.id)::bigint as ledger_entries,
  max(l.created_at) as last_ledger_at
from public.avesso_wallets w
left join public.avesso_wallet_ledger l on l.user_id=w.user_id
group by w.user_id,w.balance,w.lifetime_earned,w.lifetime_spent;
