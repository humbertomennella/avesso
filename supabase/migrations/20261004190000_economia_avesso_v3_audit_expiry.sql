CREATE OR REPLACE FUNCTION public.avesso_trade_accept_offer(p_offer_id uuid)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_user uuid := (select auth.uid());
  v_offer public.avesso_trade_offers%rowtype;
  v_line record;
  v_owned integer;
begin
  if v_user is null then raise exception 'authentication_required'; end if;

  select * into v_offer
  from public.avesso_trade_offers
  where id=p_offer_id
  for update;

  if not found or v_offer.counterparty_id<>v_user then raise exception 'offer_not_found'; end if;
  if v_offer.status<>'pending' then return false; end if;

  if v_offer.expires_at is not null and v_offer.expires_at<=now() then
    for v_line in
      select item_id,quantity
      from public.avesso_trade_escrow
      where offer_id=p_offer_id
      order by item_id
      for update
    loop
      insert into public.avesso_user_inventory(
        user_id,item_id,quantity,acquisition_source,metadata
      )
      values(
        v_offer.proposer_id,v_line.item_id,v_line.quantity,
        'trade_expire',jsonb_build_object('offer_id',p_offer_id)
      )
      on conflict(user_id,item_id)
      do update set quantity=public.avesso_user_inventory.quantity+excluded.quantity;

      insert into private.avesso_economy_item_events(
        event_type,actor_id,to_user_id,item_id,quantity,trade_offer_id,metadata
      )
      values(
        'trade_expired',v_user,v_offer.proposer_id,
        v_line.item_id,v_line.quantity,p_offer_id,'{}'::jsonb
      );
    end loop;

    delete from public.avesso_trade_escrow where offer_id=p_offer_id;
    update public.avesso_trade_offers
    set status='expired',updated_at=now()
    where id=p_offer_id;
    return false;
  end if;

  for v_line in
    select item_id,quantity
    from public.avesso_trade_lines
    where offer_id=p_offer_id and side='request'
    order by item_id
  loop
    select quantity into v_owned
    from public.avesso_user_inventory
    where user_id=v_user and item_id=v_line.item_id
    for update;

    if coalesce(v_owned,0)<v_line.quantity then
      raise exception 'counterparty_inventory_changed';
    end if;
  end loop;

  for v_line in
    select item_id,quantity
    from public.avesso_trade_lines
    where offer_id=p_offer_id and side='request'
    order by item_id
  loop
    select quantity into v_owned
    from public.avesso_user_inventory
    where user_id=v_user and item_id=v_line.item_id
    for update;

    if v_owned=v_line.quantity then
      delete from public.avesso_user_inventory
      where user_id=v_user and item_id=v_line.item_id;
    else
      update public.avesso_user_inventory
      set quantity=quantity-v_line.quantity
      where user_id=v_user and item_id=v_line.item_id;
    end if;

    insert into public.avesso_user_inventory(
      user_id,item_id,quantity,acquisition_source,metadata
    )
    values(
      v_offer.proposer_id,v_line.item_id,v_line.quantity,
      'trade_received',
      jsonb_build_object('offer_id',p_offer_id,'from_user',v_user)
    )
    on conflict(user_id,item_id)
    do update set quantity=public.avesso_user_inventory.quantity+excluded.quantity;

    insert into private.avesso_economy_item_events(
      event_type,actor_id,from_user_id,to_user_id,item_id,quantity,trade_offer_id,metadata
    )
    values(
      'trade_accepted',v_user,v_user,v_offer.proposer_id,
      v_line.item_id,v_line.quantity,p_offer_id,jsonb_build_object('leg','request')
    );
  end loop;

  for v_line in
    select item_id,quantity
    from public.avesso_trade_escrow
    where offer_id=p_offer_id
    order by item_id
    for update
  loop
    insert into public.avesso_user_inventory(
      user_id,item_id,quantity,acquisition_source,metadata
    )
    values(
      v_user,v_line.item_id,v_line.quantity,
      'trade_received',
      jsonb_build_object('offer_id',p_offer_id,'from_user',v_offer.proposer_id)
    )
    on conflict(user_id,item_id)
    do update set quantity=public.avesso_user_inventory.quantity+excluded.quantity;

    insert into private.avesso_economy_item_events(
      event_type,actor_id,from_user_id,to_user_id,item_id,quantity,trade_offer_id,metadata
    )
    values(
      'trade_accepted',v_user,v_offer.proposer_id,v_user,
      v_line.item_id,v_line.quantity,p_offer_id,jsonb_build_object('leg','offer')
    );
  end loop;

  delete from public.avesso_trade_escrow where offer_id=p_offer_id;

  update public.avesso_trade_offers
  set status='accepted',accepted_at=now(),updated_at=now()
  where id=p_offer_id;

  return true;
end;
$function$
;

