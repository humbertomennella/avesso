CREATE OR REPLACE FUNCTION public.avesso_trade_create_offer(p_counterparty_id uuid, p_offer jsonb, p_request jsonb, p_note text DEFAULT ''::text, p_expires_at timestamp with time zone DEFAULT NULL::timestamp with time zone)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_user uuid := (select auth.uid());
  v_offer_id uuid;
  v_line jsonb;
  v_item_id uuid;
  v_quantity integer;
  v_owned integer;
begin
  if v_user is null then raise exception 'authentication_required'; end if;
  if p_counterparty_id is null or p_counterparty_id=v_user then raise exception 'invalid_counterparty'; end if;
  if not exists(select 1 from public.profiles where id=p_counterparty_id) then raise exception 'counterparty_not_found'; end if;
  if p_expires_at is not null and p_expires_at<=now() then raise exception 'invalid_expiry'; end if;
  if jsonb_typeof(p_offer)<>'array' or jsonb_array_length(p_offer)=0 then raise exception 'empty_offer'; end if;
  if jsonb_typeof(p_request)<>'array' or jsonb_array_length(p_request)=0 then raise exception 'empty_request'; end if;

  insert into public.avesso_trade_offers(proposer_id,counterparty_id,note,expires_at)
  values(v_user,p_counterparty_id,left(coalesce(p_note,''),280),p_expires_at)
  returning id into v_offer_id;

  for v_line in select * from jsonb_array_elements(p_offer) loop
    v_item_id := (v_line->>'item_id')::uuid;
    v_quantity := (v_line->>'quantity')::integer;
    if v_quantity<=0 then raise exception 'invalid_quantity'; end if;

    if not exists(
      select 1 from public.avesso_item_catalog c
      where c.id=v_item_id and c.active and c.tradable and not c.soulbound
    ) then raise exception 'item_not_tradable'; end if;

    select quantity into v_owned
    from public.avesso_user_inventory
    where user_id=v_user and item_id=v_item_id
    for update;

    if coalesce(v_owned,0)<v_quantity then raise exception 'insufficient_inventory'; end if;

    if v_owned=v_quantity then
      delete from public.avesso_user_inventory
      where user_id=v_user and item_id=v_item_id;
    else
      update public.avesso_user_inventory
      set quantity=quantity-v_quantity
      where user_id=v_user and item_id=v_item_id;
    end if;

    insert into public.avesso_trade_lines(offer_id,side,item_id,quantity)
    values(v_offer_id,'offer',v_item_id,v_quantity);

    insert into public.avesso_trade_escrow(offer_id,item_id,quantity)
    values(v_offer_id,v_item_id,v_quantity);
  end loop;

  for v_line in select * from jsonb_array_elements(p_request) loop
    v_item_id := (v_line->>'item_id')::uuid;
    v_quantity := (v_line->>'quantity')::integer;
    if v_quantity<=0 then raise exception 'invalid_quantity'; end if;

    if not exists(
      select 1 from public.avesso_item_catalog c
      where c.id=v_item_id and c.active and c.tradable and not c.soulbound
    ) then raise exception 'item_not_tradable'; end if;

    insert into public.avesso_trade_lines(offer_id,side,item_id,quantity)
    values(v_offer_id,'request',v_item_id,v_quantity);
  end loop;

  insert into private.avesso_economy_item_events(
    event_type,actor_id,from_user_id,to_user_id,trade_offer_id,metadata
  )
  values(
    'trade_created',v_user,v_user,p_counterparty_id,v_offer_id,
    jsonb_build_object('offer',p_offer,'request',p_request,'note',left(coalesce(p_note,''),280))
  );

  return v_offer_id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.avesso_trade_expire_offer(p_offer_id uuid)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_user uuid := (select auth.uid());
  v_offer public.avesso_trade_offers%rowtype;
  v_row record;
begin
  if v_user is null then raise exception 'authentication_required'; end if;

  select * into v_offer
  from public.avesso_trade_offers
  where id=p_offer_id
  for update;

  if not found or v_offer.status<>'pending' then return false; end if;
  if v_offer.expires_at is null or v_offer.expires_at>now() then return false; end if;

  for v_row in
    select item_id,quantity
    from public.avesso_trade_escrow
    where offer_id=p_offer_id
    order by item_id
    for update
  loop
    insert into public.avesso_user_inventory(
      user_id,item_id,quantity,acquisition_source,metadata
    )
    values(
      v_offer.proposer_id,v_row.item_id,v_row.quantity,
      'trade_expire',jsonb_build_object('offer_id',p_offer_id)
    )
    on conflict(user_id,item_id)
    do update set quantity=public.avesso_user_inventory.quantity+excluded.quantity;

    insert into private.avesso_economy_item_events(
      event_type,actor_id,to_user_id,item_id,quantity,trade_offer_id,metadata
    )
    values(
      'trade_expired',v_user,v_offer.proposer_id,
      v_row.item_id,v_row.quantity,p_offer_id,'{}'::jsonb
    );
  end loop;

  delete from public.avesso_trade_escrow where offer_id=p_offer_id;

  update public.avesso_trade_offers
  set status='expired',updated_at=now()
  where id=p_offer_id;

  return true;
end;
$function$
;

